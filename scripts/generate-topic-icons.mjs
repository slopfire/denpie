#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = dirname(scriptDirectory);
const configPath = join(repositoryRoot, "config/topic_icons.json");
const outputPath = join(
    repositoryRoot,
    "frontend-astro/src/lib/topic-icons.generated.ts",
);

const checkOnly = process.argv.includes("--check");

function fail(message) {
    throw new Error(`topic icon generation failed: ${message}`);
}

function readIconId(value, index) {
    if (typeof value !== "string") {
        fail(`icons[${index}] must be a string`);
    }
    const iconId = value.trim();
    const separator = iconId.indexOf(":");
    if (
        iconId.length === 0 ||
        separator <= 0 ||
        separator === iconId.length - 1 ||
        separator !== iconId.lastIndexOf(":")
    ) {
        fail(
            `icons[${index}] is not a valid Iconify ID: ${JSON.stringify(value)}`,
        );
    }
    return iconId;
}

function iconDataPath(prefix) {
    return join(
        repositoryRoot,
        "frontend-astro/node_modules",
        `@iconify-json/${prefix}/icons.json`,
    );
}

async function loadIconData(iconId) {
    const separator = iconId.indexOf(":");
    const prefix = iconId.slice(0, separator);
    const name = iconId.slice(separator + 1);
    let collection;
    try {
        collection = JSON.parse(await readFile(iconDataPath(prefix), "utf8"));
    } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        fail(`could not load @iconify-json/${prefix}: ${message}`);
    }
    const icon = collection.icons?.[name];
    if (icon === undefined) {
        fail(
            `allowlisted icon ${iconId} is missing from @iconify-json/${prefix}`,
        );
    }
    return {
        ...icon,
        width: icon.width ?? collection.width,
        height: icon.height ?? collection.height,
    };
}

function renderModule(entries) {
    const ids = entries.map(({ id }) => id);
    const data = entries
        .map(
            ({ id, icon }) =>
                `  ${JSON.stringify(id)}: ${JSON.stringify(icon)}`,
        )
        .join(",\n");
    const idList = ids.map((id) => `  ${JSON.stringify(id)}`).join(",\n");

    return `// Generated by scripts/generate-topic-icons.mjs. Do not edit by hand.
// Source: config/topic_icons.json

import { addIcon, Icon as OfflineIcon } from "@iconify/react/offline";

export const TOPIC_ICON_FALLBACK = "lucide:tag";

export const TOPIC_ICON_IDS = [
${idList}
] satisfies readonly string[];

export const TOPIC_ICON_DATA: Readonly<
  Record<string, { readonly body: string; readonly width?: number; readonly height?: number }>
> = {
${data}
};

for (const [id, icon] of Object.entries(TOPIC_ICON_DATA)) {
  addIcon(id, icon);
}

/** Return a trimmed string at the boundary before allowlist lookup. */
export function normalizeTopicIconId(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

/** Return an offline-registered allowlisted ID, or the tag fallback. */
export function lookupTopicIconId(value: unknown): string {
  const normalized = normalizeTopicIconId(value);
  return TOPIC_ICON_DATA[normalized] === undefined
    ? TOPIC_ICON_FALLBACK
    : normalized;
}

/** Return the offline icon data selected by an arbitrary persisted value. */
export function lookupTopicIconData(value: unknown): {
  readonly body: string;
  readonly width?: number;
  readonly height?: number;
} {
  return TOPIC_ICON_DATA[lookupTopicIconId(value)];
}

export const TopicIcon = OfflineIcon;
`;
}

async function formatModule(source) {
    const prettierPath = join(
        repositoryRoot,
        "frontend-astro/node_modules/prettier/index.mjs",
    );
    try {
        const prettier = await import(pathToFileURL(prettierPath).href);
        const config = await prettier.resolveConfig(outputPath, {
            editorconfig: true,
        });
        return await prettier.format(source, {
            ...config,
            filepath: outputPath,
        });
    } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        fail(`could not format generated TypeScript with Prettier: ${message}`);
    }
}

async function main() {
    let config;
    try {
        config = JSON.parse(await readFile(configPath, "utf8"));
    } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        fail(`could not read ${configPath}: ${message}`);
    }
    if (
        config === null ||
        typeof config !== "object" ||
        !Array.isArray(config.icons)
    ) {
        fail("config/topic_icons.json must contain an icons array");
    }

    const ids = config.icons.map(readIconId);
    if (new Set(ids).size !== ids.length) fail("icons contains duplicate IDs");
    if (!ids.includes("lucide:tag")) {
        fail("config/topic_icons.json must include the lucide:tag fallback");
    }
    const entries = await Promise.all(
        ids.map(async (id) => ({ id, icon: await loadIconData(id) })),
    );
    const generated = await formatModule(renderModule(entries));

    let existing = "";
    try {
        existing = await readFile(outputPath, "utf8");
    } catch (error) {
        if (error.code !== "ENOENT") throw error;
    }
    if (checkOnly) {
        if (existing !== generated) {
            console.error(
                `${outputPath} is out of date; run generate:topic-icons`,
            );
            process.exitCode = 1;
        }
        return;
    }
    if (existing !== generated) await writeFile(outputPath, generated);
}

main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
});
